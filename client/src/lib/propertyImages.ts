/** Deal fields used only for gallery visuals — never mutates engine math. */
export type VisualDealState = {
  status?: string | null;
  rentalRehabActive?: boolean | null;
  completedRepairIds?: string[] | null;
};

/**
 * Resolve which condition interiors should show.
 * Listing tag is ground truth on the market; after rehab finishes, galleries
 * flip to renovated (Excellent) without changing property.conditionTag.
 */
export function resolveVisualConditionTag(
  listingConditionTag: string,
  deal?: VisualDealState | null
): string {
  if (!deal) return listingConditionTag;

  const status = deal.status || '';
  const midRehab = status === 'in_rehab' || !!deal.rentalRehabActive;
  if (midRehab) return listingConditionTag;

  if (status === 'ready_to_list' || status === 'listing' || status === 'leasing') {
    return 'Excellent';
  }

  const repairsDone = (deal.completedRepairIds?.length ?? 0) > 0;
  if (repairsDone) return 'Excellent';

  // Fixer/Fair rental that is occupied and not in rehab ⇒ initial rehab finished
  if (status === 'active_rental' && getConditionTier(listingConditionTag) <= 2) {
    return 'Excellent';
  }

  return listingConditionTag;
}

export const getPropertyInteriorImages = (propertyName: string): Array<{ type: string; label: string; url: string }> => {
  return propertySpecificInteriors[propertyName] || [];
};

export const getConditionAdjustedInteriors = (
  propertyName: string,
  conditionTag: string,
  _price: number,
  options?: { listingConditionTag?: string; deal?: VisualDealState | null }
): Array<{ type: string; label: string; url: string }> => {
  const specificInteriors = propertySpecificInteriors[propertyName];
  if (!specificInteriors || specificInteriors.length === 0) return [];

  const listingTag = options?.listingConditionTag ?? conditionTag;
  const visualTag = options?.deal
    ? resolveVisualConditionTag(listingTag, options.deal)
    : conditionTag;
  const tier = getConditionTier(visualTag);
  const listingTier = getConditionTier(listingTag);
  const showRenovatedLabels = tier >= 4 && listingTier <= 2;

  // Fixer / needs-work: show heavy repair interiors so quality matches the listing
  if (tier <= 1) {
    return specificInteriors.map((room) => ({
      ...room,
      url: fixerUpperInteriors[room.type] || room.url,
      label: room.type === 'basement'
        ? 'Basement — needs work'
        : `${room.label} — needs repair`,
    }));
  }

  // Fair / dated: cosmetic update interiors
  if (tier === 2) {
    return specificInteriors.map((room) => {
      // Keep property-specific basement / systems photos when available
      if (room.type === 'basement') return room;
      return {
        ...room,
        url: datedInteriors[room.type] || room.url,
        label: `${room.label} — dated`,
      };
    });
  }

  // Good / Excellent / post-rehab: property-specific renovated interiors
  if (showRenovatedLabels) {
    return specificInteriors.map((room) => ({
      ...room,
      label: room.type === 'basement'
        ? 'Basement — renovated'
        : `${room.label.replace(/ — .*$/, '')} — renovated`,
    }));
  }

  return specificInteriors;
};

