const conditionTiers: Record<string, number> = {
  'Fixer-Upper': 1,
  'Needs Repairs': 1,
  'Needs-work': 1,
  'Dated': 2,
  'Fair': 2,
  'Cosmetic': 3,
  'Good': 3,
  'Turnkey': 4,
  'Excellent': 4,
};

function getPriceTier(price: number): number {
  if (price < 250000) return 1;
  if (price < 400000) return 2;
  if (price < 600000) return 3;
  return 4;
}

const datedInteriors: Record<string, string> = {
  kitchen: interiorKitchenDated,
  bathroom: interiorBathroomDated,
  living: interiorLivingRoomDated,
  basement: interiorBasementClean,
};

const fixerUpperInteriors: Record<string, string> = {
  kitchen: interiorKitchenExtreme,
  bathroom: interiorBathroomExtreme,
  living: interiorLivingRoomExtreme,
  basement: interiorBasementExtreme,
};

export const getPropertyInteriorImages = (propertyName: string): Array<{ type: string; label: string; url: string }> => {
  return propertySpecificInteriors[propertyName] || [];
};

export const getConditionAdjustedInteriors = (
  propertyName: string,
  conditionTag: string,
  _price: number
): Array<{ type: string; label: string; url: string }> => {
  const specificInteriors = propertySpecificInteriors[propertyName];
  if (!specificInteriors || specificInteriors.length === 0) return [];

  const tier = conditionTiers[conditionTag] ?? 3;

  // Fixer / needs-work: show heavy repair interiors so quality matches the listing
  if (tier <= 1) {
    return specificInteriors.map((room) => ({
      ...room,
      url: fixerUpperInteriors[room.type] || room.url,
      label: room.type === 'basement'
        ? 'Basement — needs work'
        : `${room.label} — needs repair`,
    }));
  }

  // Fair / dated: cosmetic update interiors
  if (tier === 2) {
    return specificInteriors.map((room) => {
      // Keep property-specific basement / systems photos when available
      if (room.type === 'basement') return room;
      return {
        ...room,
        url: datedInteriors[room.type] || room.url,
        label: `${room.label} — dated`,
      };
    });
  }

  // Good / Excellent / turnkey: keep property-specific interiors
  return specificInteriors;
};

